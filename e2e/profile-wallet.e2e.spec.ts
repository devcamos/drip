import { expect, test } from "@playwright/test";

test("a user opens profile settings and manages multiple sample holdings and credit cards", async ({ page }) => {
  const writes: string[] = [];
  page.on("request", request => { if (new URL(request.url()).pathname.startsWith("/api/") && request.method() !== "GET") writes.push(request.url()); });
  await page.route("https://www.tradingview-widget.com/**", route => route.fulfill({ contentType: "text/html", body: "<!doctype html><p>Chart transport fixture, no market data.</p>" }));
  await page.route("**/api/exchange-rates?base=USD", route => route.fulfill({ json: { base: "USD", quote: "GBP", rate: 0.75, date: new Date().toISOString().slice(0, 10), source: "Frankfurter" } }));
  await page.goto("/prototype/welcome");
  await page.getByRole("button", { name: "Enter demo", exact: true }).click();
  const avatar = page.getByRole("button", { name: "Open profile and settings" });
  await avatar.click();
  const profile = page.getByRole("dialog", { name: "Profile & settings" });
  await expect(profile.getByText("demo_grower", { exact: true })).toBeVisible();
  await profile.getByRole("button", { name: "Yearly", exact: true }).click();
  await page.keyboard.press("Escape");
  await expect(profile).not.toBeVisible();
  await expect(avatar).toBeFocused();
  await expect(page.getByRole("region", { name: "Estimated income" })).toContainText("£340.00");
  await page.getByRole("button", { name: "Add an example account" }).click();
  await page.getByRole("dialog").getByRole("button", { name: /Stocks & funds/ }).click();
  const stock = page.getByRole("dialog", { name: "Digital Realty share price" });
  await expect(stock.locator("iframe")).toHaveAttribute("title", "Digital Realty delayed share-price chart");
  await stock.getByLabel("Current price per share (USD)").fill("100");
  await stock.getByRole("button", { name: "Update demo value" }).click();
  await expect(stock.getByLabel("Holding performance")).toContainText("-£300.00 (-16.67%)");
  await stock.getByRole("button", { name: "Back to accounts", exact: true }).click();
  await expect(page.getByRole("button", { name: /Realty Income.*£2,500/ })).toBeVisible();
  await expect(page.getByRole("button", { name: /Digital Realty.*£1,500/ })).toBeVisible();
  await page.getByRole("button", { name: "Add an example account" }).click();
  await page.getByRole("dialog").getByRole("button", { name: /Credit card/ }).click();
  await page.getByRole("button", { name: "Edit credit card", exact: true }).click();
  const editor = page.getByRole("dialog", { name: "Edit credit card" });
  await editor.getByLabel("Amount owed (£)", { exact: true }).fill("1000");
  await editor.getByLabel("Planned payment (£, optional)", { exact: true }).fill("80");
  await editor.getByRole("button", { name: "Save changes", exact: true }).click();
  await expect(page.getByRole("button", { name: /Barclaycard.*£1,200/ })).toBeVisible();
  await expect(page.getByRole("button", { name: /Lloyds credit card.*£1,000/ })).toBeVisible();
  await expect(page.getByRole("region", { name: "Money overview" })).toContainText("£6,800.00");
  await expect(page.getByRole("region", { name: "Estimated income" })).toContainText("£404.00");
  const ids = await page.locator("[id]").evaluateAll(nodes => nodes.map(node => node.id));
  expect(new Set(ids).size).toBe(ids.length);
  await avatar.click();
  await expect(profile.getByText("Holdings", { exact: true }).locator(".." )).toContainText("2");
  await expect(profile.getByText("Credit cards", { exact: true }).locator(".." )).toContainText("2");
  await profile.getByRole("button", { name: "Sign out of demo" }).click();
  await expect(page.getByRole("button", { name: "Enter demo", exact: true })).toBeVisible();
  expect(writes).toEqual([]);
  expect(await page.evaluate(async () => ({ databases: await indexedDB.databases(), localKeys: Object.keys(localStorage) }))).toEqual({ databases: [], localKeys: [] });
});
